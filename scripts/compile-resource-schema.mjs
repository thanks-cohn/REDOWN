// Authoritative input: agent/resources/evidence.schema.json. Generated validator is browser-safe.
import {readFile,writeFile} from 'node:fs/promises';
import Ajv from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standalone from 'ajv/dist/standalone/index.js';
import {build} from 'esbuild';
const schema=JSON.parse(await readFile('agent/resources/evidence.schema.json','utf8'));
const ajv=new Ajv({code:{source:true,esm:true},strict:true});addFormats(ajv);
const code=standalone(ajv,ajv.compile(schema));
const output=await build({stdin:{contents:code,resolveDir:process.cwd(),sourcefile:'resource-evidence-validator.mjs'},bundle:true,platform:'browser',format:'esm',minify:true,write:false});
const generated='// Generated by scripts/compile-resource-schema.mjs; do not edit.\n'+output.outputFiles[0].text;
const path='extension/file-engine/resource-evidence-validator.mjs';
if(process.argv.includes('--check')){if(await readFile(path,'utf8')!==generated)throw Error('RESOURCE_SCHEMA_GENERATED_DRIFT');}
else await writeFile(path,generated);
const contracts=JSON.parse(await readFile('agent/resources/contracts.json','utf8'));
const names={};for(const operation of contracts.operations){const name=operation.id.split('.').at(-1),id='urn:redown:resources:input:'+name;ajv.addSchema(operation.inputSchema,id);names[name]=id;}
const inputs=await build({stdin:{contents:standalone(ajv,names),resolveDir:process.cwd(),sourcefile:'resource-input-validators.mjs'},bundle:true,platform:'browser',format:'esm',minify:true,write:false});
const inputGenerated='// Generated from agent/resources/contracts.json; do not edit.\n'+inputs.outputFiles[0].text;
const inputPath='extension/file-engine/resource-input-validators.mjs';
if(process.argv.includes('--check')){if(await readFile(inputPath,'utf8')!==inputGenerated)throw Error('RESOURCE_INPUT_SCHEMA_GENERATED_DRIFT');}else await writeFile(inputPath,inputGenerated);
